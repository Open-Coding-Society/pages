// Sets (or replaces) a button's icon and label, keeping its colour classes.
export function setIconLabel(button, icon, label) {
    button.classList.add('ocs__btn--icon');
    const slot = document.createElement('span');
    slot.className = 'ocs__btn-icon';
    slot.setAttribute('aria-hidden', 'true');
    slot.innerHTML = `<svg viewBox="0 0 16 16" xmlns="http://www.w3.org/2000/svg"><path d="${ICONS[icon]}"/></svg>`;
    const text = document.createElement('span');
    text.textContent = label;
    button.replaceChildren(slot, text);
}

// A new card button with an icon and label.
export function iconButton(className, icon, label) {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = className;
    setIconLabel(button, icon, label);
    return button;
}
