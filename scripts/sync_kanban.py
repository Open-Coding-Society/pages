#!/usr/bin/env python3
"""Regenerate the kanban board section in the Shoreline capstone page from
the live GitHub Project board (vanshikak210/projects/8).

Run by .github/workflows/sync-kanban.yml. Requires `gh` to be authenticated
(GH_TOKEN env var with the `read:project` scope) when run outside that
workflow.
"""

import html
import json
import subprocess
import sys
from pathlib import Path

PROJECT_OWNER = "vanshikak210"
PROJECT_NUMBER = "8"
PROJECT_URL = f"https://github.com/users/{PROJECT_OWNER}/projects/{PROJECT_NUMBER}"

TARGET_FILE = (
    Path(__file__).resolve().parent.parent
    / "_posts/capstone/2026-09-11-shoreline-volunteer-capstone.md"
)
START_MARKER = "<!-- KANBAN:START (auto-generated by scripts/sync_kanban.py — do not edit by hand) -->"
END_MARKER = "<!-- KANBAN:END -->"

ASSIGNEE_NAMES = {
    "nkasse12": "Nitya",
    "vanshikak210": "Vanshika",
}


def gh_json(*args):
    result = subprocess.run(
        ["gh", *args, "--format", "json"],
        capture_output=True,
        text=True,
        check=True,
    )
    return json.loads(result.stdout)


def display_name(word):
    return word.capitalize() if word.islower() else word


def column_title(status):
    return " ".join(display_name(w) for w in status.split(" "))


def display_assignee(login):
    return ASSIGNEE_NAMES.get(login, login)


def build_html(columns, counts):
    lines = [START_MARKER, '<div class="shoreline-kanban">']
    for status, items in columns:
        lines.append('    <div class="shoreline-kanban__column">')
        lines.append(
            f'        <div class="shoreline-kanban__column-title">{html.escape(column_title(status))} '
            f'<span class="shoreline-kanban__count">{counts[status]}</span></div>'
        )
        for item in items:
            title = html.escape(item["title"])
            assignees = item.get("assignees") or []
            lines.append(
                f'        <a class="shoreline-kanban__card" href="{PROJECT_URL}" target="_blank" rel="noopener">'
            )
            lines.append(f"            <strong>{title}</strong>")
            if assignees:
                names = ", ".join(display_assignee(a) for a in assignees)
                lines.append(f"            <span>{html.escape(names)}</span>")
            lines.append("        </a>")
        lines.append("    </div>")
    lines.append("</div>")
    lines.append(END_MARKER)
    return "\n".join(lines)


def main():
    fields = gh_json("project", "field-list", PROJECT_NUMBER, "--owner", PROJECT_OWNER)
    status_field = next(f for f in fields["fields"] if f["name"] == "Status")
    status_order = [opt["name"] for opt in status_field["options"]]

    items = gh_json("project", "item-list", PROJECT_NUMBER, "--owner", PROJECT_OWNER, "--limit", "200")["items"]

    columns = {status: [] for status in status_order}
    for item in items:
        status = item.get("status")
        if status not in columns:
            columns.setdefault(status, [])  # unknown/new status column, append at end
        columns[status].append(item)

    ordered = [(status, columns[status]) for status in columns]
    counts = {status: len(items_) for status, items_ in ordered}

    new_block = build_html(ordered, counts)

    text = TARGET_FILE.read_text()
    start = text.find(START_MARKER)
    end = text.find(END_MARKER)
    if start == -1 or end == -1:
        print("Kanban markers not found in target file", file=sys.stderr)
        sys.exit(1)
    end += len(END_MARKER)

    updated = text[:start] + new_block + text[end:]
    if updated != text:
        TARGET_FILE.write_text(updated)
        print("Kanban board updated.")
    else:
        print("Kanban board already up to date.")


if __name__ == "__main__":
    main()
